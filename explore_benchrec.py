        # A joined row is not the same as a usable label — check the label CONTENT.
        R.h3("Row present vs. label actually populated — these are different questions")
        R.p("A 100% join rate says every B row finds a solution row. It does not say every "
            "solution row carries an answer. Checking the contents of `targetAllocation`:")
        n_blank = int((sol["targetAllocation"].str.strip() == "").sum())
        n_filled = len(sol) - n_blank
