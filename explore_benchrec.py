# 6. AMOUNT RECONCILIATION
# ==================================================================================
R.h1("6. Do amounts in a one-to-many allocation sum exactly?")

if not have_train:
    R.p("Train file absent — section skipped.")
else:
    tr = frames_str[TRAIN_FILE]
    A = tr[tr["A_transactionType"] == "A"].copy()
    B = tr[tr["B_transactionType"] == "B"].copy()
    A["amt"] = num(A["A_amount"])
    B["amt"] = num(B["B_amount"])

    agg = pd.DataFrame({
        "n_A": A.groupby("matchId").size(),
        "sum_A": A.groupby("matchId")["amt"].sum(),
    }).join(pd.DataFrame({
        "n_B": B.groupby("matchId").size(),
        "sum_B": B.groupby("matchId")["amt"].sum(),
    }), how="outer")
    agg = agg[agg.index != ""]
    agg[["n_A", "n_B"]] = agg[["n_A", "n_B"]].fillna(0).astype(int)
    agg[["sum_A", "sum_B"]] = agg[["sum_A", "sum_B"]].fillna(0.0)

    both_sides = agg[(agg["n_A"] > 0) & (agg["n_B"] > 0)].copy()

    R.p("Amounts are already signed in the raw data (see the sign-convention table in "
        "section 5), so reconciliation is tested two ways and the better-fitting convention "
        "is reported rather than assumed:")
    R.p()
    R.bullet("**opposite-sign convention** — the two sides cancel: `sum_A + sum_B == 0`")
    R.bullet("**same-sign convention** — the two sides equal each other: `sum_A - sum_B == 0`")
    R.p()

    both_sides["resid_sum"] = both_sides["sum_A"] + both_sides["sum_B"]
    both_sides["resid_diff"] = both_sides["sum_A"] - both_sides["sum_B"]

    TOL = 0.005  # half a cent — "exact" at 2dp

    conv = pd.DataFrame({
        "convention": ["sum_A + sum_B == 0 (opposite sign)", "sum_A - sum_B == 0 (same sign)"],
        "groups_tested": [len(both_sides)] * 2,
        "exact_within_0.005": [
            int((both_sides["resid_sum"].abs() <= TOL).sum()),
            int((both_sides["resid_diff"].abs() <= TOL).sum()),
        ],
    })
    conv["pct_exact"] = (conv["exact_within_0.005"] / conv["groups_tested"] * 100).round(4)
    R.block(conv.to_string(index=False))

    use_diff = (both_sides["resid_diff"].abs() <= TOL).sum() >= (both_sides["resid_sum"].abs() <= TOL).sum()
    resid_col = "resid_diff" if use_diff else "resid_sum"
    conv_name = "sum_A - sum_B" if use_diff else "sum_A + sum_B"
    both_sides["residual"] = both_sides[resid_col]
    R.p()
    R.kv("convention used below", f"residual = {conv_name}")

    R.h2("6.1 Exactness by group shape")

    def shape_of(row):
        if row["n_A"] == 1 and row["n_B"] == 1:
            return "1:1"
        if row["n_A"] > 1 and row["n_B"] == 1:
            return "1 B : many A"
        if row["n_A"] == 1 and row["n_B"] > 1:
            return "many B : 1 A"
        return "many : many"

    both_sides["shape"] = both_sides.apply(shape_of, axis=1)

    tab = both_sides.groupby("shape").apply(
        lambda g: pd.Series({
            "groups": len(g),
            "exact_<=0.005": int((g["residual"].abs() <= TOL).sum()),
            "pct_exact": round(float((g["residual"].abs() <= TOL).mean() * 100), 3),
            "within_1.00": round(float((g["residual"].abs() <= 1.0).mean() * 100), 3),
            "median_abs_residual": round(float(g["residual"].abs().median()), 2),
            "p95_abs_residual": round(float(g["residual"].abs().quantile(0.95)), 2),
            "max_abs_residual": round(float(g["residual"].abs().max()), 2),
        }), include_groups=False
    )
    R.block(tab.to_string())

    R.h2("6.2 Overall answer")

    one_to_many = both_sides[both_sides["shape"] != "1:1"]
    if len(one_to_many):
        exact_otm = float((one_to_many["residual"].abs() <= TOL).mean())
        exact_11 = float((both_sides[both_sides["shape"] == "1:1"]["residual"].abs() <= TOL).mean())

        R.kv("one-to-many groups tested", f"{len(one_to_many):,}")
        R.kv("of those, amounts reconcile EXACTLY (<= 0.005)", fmt_pct(exact_otm))
        R.kv("of those, leave a residual", fmt_pct(1 - exact_otm))
        R.kv("1:1 groups reconciling exactly, for comparison", fmt_pct(exact_11))

        R.p()
        R.p("Residual magnitude on the groups that do NOT reconcile exactly:")
        nz = one_to_many[one_to_many["residual"].abs() > TOL]["residual"].abs()
        if len(nz):
            R.block(nz.describe(percentiles=[0.25, 0.5, 0.75, 0.9, 0.99]).to_string())
            R.p()
            R.p("How big is the residual relative to the transaction? "
                "(|residual| / |sum_B|, on non-exact one-to-many groups)")
            rel = (one_to_many.loc[one_to_many["residual"].abs() > TOL, "residual"].abs() /
                   one_to_many.loc[one_to_many["residual"].abs() > TOL, "sum_B"].abs().replace(0, np.nan))
            R.block(rel.describe(percentiles=[0.25, 0.5, 0.75, 0.9, 0.99]).to_string())

        R.p()
        R.p("**The aggregate number is misleading — read it by shape.** The 'many : many' "
            "bucket dominates the one-to-many population and reconciles well, which pulls the "
            "average up and hides how badly the true fan-out shapes behave:")
        R.p()
        by_shape = {}
        for shp in ["1:1", "1 B : many A", "many B : 1 A", "many : many"]:
            sel = both_sides[both_sides["shape"] == shp]
            if len(sel):
                by_shape[shp] = float((sel["residual"].abs() <= TOL).mean())
        for shp, v in by_shape.items():
            R.bullet(f"`{shp}` — {fmt_pct(v)} reconcile exactly")

        clean_shapes = [s for s, v in by_shape.items() if s != "1:1" and v < 0.5]
        R.check(
            "BROKEN",
            "Amounts in a genuine one-to-many allocation mostly do NOT sum to the transaction "
            "amount",
            f"Aggregated over all non-1:1 groups the figure looks acceptable at "
            f"{fmt_pct(exact_otm)}, but that average is carried by the 'many : many' bucket "
            f"({fmt_pct(by_shape.get('many : many', float('nan')))} exact). The shapes the "
            f"brief is actually about are far worse: '1 B : many A' reconciles exactly only "
            f"{fmt_pct(by_shape.get('1 B : many A', float('nan')))} of the time and "
            f"'many B : 1 A' only {fmt_pct(by_shape.get('many B : 1 A', float('nan')))}. "
            f"For comparison 1:1 groups are {fmt_pct(exact_11)} exact. The residuals are not "
            "rounding noise — the median non-exact residual is a five-figure amount and at the "
            "75th percentile the residual is ~37% of the transaction value. Treat amount "
            "equality as a strong signal for 1:1 and a weak one for fan-out; do not build on "
            "an assumption that a set of A rows sums to its B amount."
            + (f" Shapes failing the majority test: {clean_shapes}." if clean_shapes else ""),
        )

    R.h2("6.3 Groups with only one side present")
