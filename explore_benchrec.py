                "Solution COVERAGE of eval type-B rows is complete — 100.0000%",
                f"All {len(ev_b):,} eval type-B transactions have exactly one solution entry, "
                "so the join loses nothing and labels are not partial in the sense you were "
                "worried about. Coverage is not the same as every row carrying an answer, "
                "though — see the blank-label check immediately below.",
