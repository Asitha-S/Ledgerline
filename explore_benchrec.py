# ----------------------------------------------------------------------------------
# Reporter: tee to stdout and to a markdown buffer.
# ----------------------------------------------------------------------------------
class Reporter:
    def __init__(self):
        self.buf = io.StringIO()
        self.checks = []  # (status, title, detail)

    # --- the two sinks are kept strictly separate: _out -> stdout, _md -> report file ---
    def _out(self, text=""):
        print(text)

    def _md(self, text=""):
        self.buf.write(text + "\n")

    def h1(self, text):
        self._out()
        self._out("=" * 100)
        self._out(text.upper())
        self._out("=" * 100)
        self._md(f"\n# {text}\n")

    def h2(self, text):
        self._out()
        self._out("-" * 100)
        self._out(text)
        self._out("-" * 100)
        self._md(f"\n## {text}\n")

    def h3(self, text):
        self._out()
        self._out(f"### {text}")
        self._md(f"\n### {text}\n")

    def p(self, text=""):
        self._out(text)
        self._md(text)

    def bullet(self, text):
        self._out(f"  - {text}")
        self._md(f"- {text}")

    def kv(self, key, value):
        self._out(f"  {key:<48} {value}")
        self._md(f"- **{key}**: {value}")

    def block(self, text):
        """Pre-formatted block (tables, sample rows). Fenced in markdown."""
        self._out(text)
        self._md("\n```text\n" + text.rstrip("\n") + "\n```\n")

    def check(self, status, title, detail):
        """status: OK | BROKEN | NUANCED"""
        self.checks.append((status, title, detail))
        marker = {"OK": "[OK]     ", "BROKEN": "[BROKEN] ", "NUANCED": "[NUANCE] "}[status]
        self._out(f"  {marker} {title}")
        self._out(f"           {detail}")
        self._md(f"- **{status} — {title}**  \n  {detail}")

    def save(self, path):
        # Markdown header for the whole document
        header = (
            "# BenchRec cash reconciliation — data exploration report\n\n"
            "_Generated by `explore_benchrec.py`. Descriptive only: no matching logic, "
            "no modelling, no plots._\n"
        )
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(header)
            fh.write(self.buf.getvalue())


