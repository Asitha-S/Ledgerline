    R.p()
    R.bullet("`solution.B_id` -> `eval.B_id`.")
    R.bullet(f"`B_id` is unique in the solution file: "
             f"{sol.B_id.nunique():,} distinct values across {len(sol):,} rows "
             f"({'unique' if sol.B_id.nunique() == len(sol) else 'NOT unique'}).")
