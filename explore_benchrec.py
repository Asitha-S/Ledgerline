def load_typed(path):
    """Natural dtype inference — used for reporting dtypes and null counts."""
    return pd.read_csv(path, low_memory=False)


def load_str(path):
    """Everything as string, blanks preserved as '' — used for structural logic so that
    'missing' is unambiguous and IDs never become floats."""
    return pd.read_csv(path, dtype=str, keep_default_na=False, na_values=[])


def fmt_pct(x):
    return f"{100.0 * x:.4f}%"


def counts_table(series, name, top=None):
    vc = series.value_counts(dropna=False)
    if top is not None:
        vc = vc.head(top)
    df = vc.rename("count").to_frame()
    df["pct"] = (df["count"] / max(len(series), 1) * 100).round(4)
    df.index.name = name
    return df.to_string()


def num(series):
    return pd.to_numeric(series, errors="coerce")


def parse_alloc(value):
    """`targetAllocation` uses TWO encodings in the same column:

      1. a bare allocation key            ->  USD_2023-03-05_ACC#00001_66912  ...
      2. a bracketed, comma-separated set ->  [USD_..._KEY1,USD_..._KEY2]

    Returns the allocation key(s) as a list. Verified safe: no individual allocation
    key anywhere in the data contains a comma, so splitting on ',' cannot break a key.
    """
    if value is None:
        return []
    s = str(value).strip()
    if s == "" or s.lower() == "nan":
        return []
    if s.startswith("[") and s.endswith("]"):
        return [p for p in s[1:-1].split(",") if p != ""]
    return [s]


def alloc_set_size(value):
    return len(parse_alloc(value))


