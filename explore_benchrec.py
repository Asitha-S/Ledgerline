# 4. ALLOCATION STRUCTURE
# ==================================================================================
R.h1("4. Allocation structure")

R.h2("4.1 Does the data really carry the A/B type distinction?")

if not have_train:
    R.p("Train file absent — section skipped.")
else:
    tr = frames_str[TRAIN_FILE]

    R.p("Yes — but **not in the shape the brief assumes**, and this is the single most "
        "important structural finding in the report.")
    R.p()
    R.p("The expectation was one column holding 'A' or 'B'. In fact the files are in a "
        "**long / stacked layout with a doubled column set**:")
    R.p()
    R.bullet("There are TWO type columns, `A_transactionType` and `B_transactionType`.")
    R.bullet("Each data row is a SINGLE transaction. If it is a type-A row, "
             "`A_transactionType == 'A'` and every `A_*` column is populated while every "
             "`B_*` column is blank. If it is a type-B row, the mirror holds.")
    R.bullet("A row is NEVER an A/B pair. The pairing is carried by **`matchId`** — the "
             "A rows and B rows that reconcile together share one `matchId`.")
    R.p()

    a_mask = tr["A_transactionType"] == "A"
    b_mask = tr["B_transactionType"] == "B"
    both = (a_mask & b_mask).sum()
    neither = (~a_mask & ~b_mask).sum()

    R.h3("Proof, on the train file")
    R.kv("rows where A_transactionType == 'A'", f"{int(a_mask.sum()):,}")
    R.kv("rows where B_transactionType == 'B'", f"{int(b_mask.sum()):,}")
    R.kv("rows that are BOTH A and B", f"{int(both):,}")
    R.kv("rows that are NEITHER", f"{int(neither):,}")
    R.p()
    R.block("A_transactionType\n" + counts_table(tr["A_transactionType"].replace("", "<blank>"), "value")
            + "\n\nB_transactionType\n" + counts_table(tr["B_transactionType"].replace("", "<blank>"), "value"))

    R.p()
    R.p("Cross-check that the blanking is truly structural — fill rate of key columns, "
        "split by row type:")
    fill = pd.DataFrame({
        "column": ["A_id", "A_allocation", "A_amount", "B_id", "B_amount", "targetAllocation"],
        "fill_rate_on_A_rows": [
            round(float((tr.loc[a_mask, c] != "").mean() * 100), 3)
            for c in ["A_id", "A_allocation", "A_amount", "B_id", "B_amount", "targetAllocation"]
        ],
        "fill_rate_on_B_rows": [
            round(float((tr.loc[b_mask, c] != "").mean() * 100), 3)
            for c in ["A_id", "A_allocation", "A_amount", "B_id", "B_amount", "targetAllocation"]
        ],
    })
    R.block(fill.to_string(index=False))

    R.check(
        "BROKEN",
        "There is no single A/B column — there are two, and the layout is long, not paired",
        "The distinction is carried by the COLUMN PREFIX plus the pair of columns "
        "`A_transactionType` / `B_transactionType`. Any code that assumes one row = one "
        "candidate A/B pair will be wrong: one row = one transaction, and the pairing lives "
        "in `matchId`.",
    )

    if both == 0 and neither == 0:
        R.check(
            "OK",
            "The A/B partition is clean",
            f"Every one of the {len(tr):,} train rows is exactly one of A or B — no row is "
            "both, none is neither.",
        )

    # ------------------------------------------------------------------
    R.h2("4.2 What the label actually looks like")

    B = tr[b_mask]
    labelled = B[B["targetAllocation"] != ""].copy()
    labelled["n_alloc"] = labelled["targetAllocation"].map(alloc_set_size)

    R.p("`targetAllocation` is a delimited string — but **the column uses two different "
        "encodings**, and missing this is the easiest way to silently corrupt a label set:")
    R.p()
    R.bullet("**Bare key** — a single allocation key, e.g. `USD_2015-03-20_ACC#00001_664...`")
    R.bullet("**Bracketed set** — several keys in one field, comma-separated inside square "
             "brackets: `[USD_..._KEY1,USD_..._KEY2]`")
    R.p()
    bracketed = labelled["targetAllocation"].str.startswith("[")
    R.kv("labelled B rows in train", f"{len(labelled):,}")
    R.kv("bare single key", f"{int((~bracketed).sum()):,} ({fmt_pct((~bracketed).mean())})")
    R.kv("bracketed multi-key set",
         f"{int(bracketed.sum()):,} ({fmt_pct(bracketed.mean())})")
    R.p()
    n_comma_keys = int(tr.loc[a_mask, "A_allocation"].str.contains(",").sum())
    R.p("Comma-splitting is safe here: verified that no individual allocation key anywhere in "
        f"the data contains a comma (A_allocation values containing ',': {n_comma_keys}).")

    R.check(
        "BROKEN",
        "`targetAllocation` is NOT always one key — it can be a bracketed SET of keys",
        f"{int(bracketed.sum()):,} of {len(labelled):,} labelled train B rows "
        f"({fmt_pct(bracketed.mean())}) hold a `[key1,key2,...]` list. Reading this column as "
        "a plain string treats each distinct list as its own unique label and makes the "
        "multi-target cases unlearnable and unscoreable. It must be parsed as a set.",
    )

    R.h3("Example of each encoding")
    R.block("BARE:\n" + repr(labelled.loc[~bracketed, "targetAllocation"].iloc[0]) +
            "\n\nBRACKETED:\n" + repr(labelled.loc[bracketed, "targetAllocation"].iloc[0]) +
            "\n\nBRACKETED, parsed into its component keys:\n" +
            "\n".join(f"  [{i}] {repr(k)}" for i, k in
                      enumerate(parse_alloc(labelled.loc[bracketed, "targetAllocation"].iloc[0]))))

    R.h3("Anatomy of a single allocation key")
    exploded = labelled["targetAllocation"].map(parse_alloc).explode().dropna()
    sample_key = exploded.iloc[0]
    R.block(repr(sample_key))
    R.p()
    parts = exploded.str.split("_", n=3, expand=True)
    n_parts = exploded.str.count("_") + 1
    R.kv("underscore-delimited fields (min/median/max)",
         f"{int(n_parts.min())} / {int(n_parts.median())} / {int(n_parts.max())}")
    R.p()
    R.p("Decoding the first three fields:")
    R.bullet(f"field 1 = currency  -> distinct values: {sorted(parts[0].unique())}")
    R.bullet(f"field 2 = a DATE    -> range {parts[1].min()} .. {parts[1].max()}")
    R.bullet(f"field 3 = account   -> distinct values: {sorted(parts[2].unique())[:10]}")
    R.bullet("field 4 = transaction attributes (long, whitespace-padded free text)")

    # Does field 2 equal the A-side value date?
    R.check(
        "NUANCED",
        "The allocation key is currency + DATE + account + attributes — the brief omitted the date",
        "The brief described the key as 'currency plus account plus transaction attributes'. "
        f"There is a fourth component: a date sits in position 2 (range {parts[1].min()} to "
        f"{parts[1].max()}). It is part of the string you must predict exactly, so it cannot "
        "be ignored.",
    )

    # Verify the parsed target SET against the A_allocations in the same matchId group.
    A = tr[a_mask]
    alloc_by_match = A.groupby("matchId")["A_allocation"].agg(set)
    lab = labelled[labelled["matchId"] != ""].copy()
    lab["group_allocs"] = lab["matchId"].map(alloc_by_match)
    lab = lab[lab["group_allocs"].notna()]
    lab["target_set"] = lab["targetAllocation"].map(lambda v: set(parse_alloc(v)))

    is_subset = [t <= g for t, g in zip(lab["target_set"], lab["group_allocs"])]
    is_equal = [t == g for t, g in zip(lab["target_set"], lab["group_allocs"])]

    R.h3("Does a B row's target set match the A_allocations in its matchId group?")
    R.kv("labelled B rows with an A-side group", f"{len(lab):,}")
    R.kv("target set is a SUBSET of the group's A_allocations", fmt_pct(np.mean(is_subset)))
    R.kv("target set EQUALS the group's A_allocation set", fmt_pct(np.mean(is_equal)))

    if np.mean(is_equal) == 1.0:
        R.check(
            "OK",
            "Once parsed as a set, targetAllocation is EXACTLY the set of distinct "
            "A_allocation keys in the same matchId group — 100.0000%",
            "No exceptions across all labelled train B rows. This nails the label definition: "
            "the target is the deduplicated set of allocation keys of the type-A ledger rows "
            "sharing the B row's matchId. It also confirms `matchId` is the pairing mechanism, "
            "and explains the bracketed encoding — brackets appear precisely when a group's A "
            "rows carry more than one distinct key.",
        )
    else:
        R.check(
            "NUANCED",
            "Parsed target set does not always equal the group's A_allocation set",
            f"subset in {fmt_pct(np.mean(is_subset))} of rows, exact equality in "
            f"{fmt_pct(np.mean(is_equal))}.",
        )

